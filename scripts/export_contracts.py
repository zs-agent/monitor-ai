"""Generate enum values/defaults, and --check to catch Python/TypeScript drift."""
from pathlib import Path
import argparse
import json
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'research-service'))
from service.contracts import TaskType, AgentRole, ActionPackage, VerificationStatus, UpdateStatus, RunStatus, QuestionStatus, SchedulerConfig

lines = ['// Generated by scripts/export_contracts.py. Do not edit enum values here.']
for name, enum in [('TaskType', TaskType), ('AgentRole', AgentRole), ('ActionPackage', ActionPackage), ('VerificationStatus', VerificationStatus), ('UpdateStatus', UpdateStatus), ('RunStatus', RunStatus), ('QuestionStatus', QuestionStatus)]:
    lines += [f'export const {name}Values = {json.dumps([x.value for x in enum])} as const', f'export type {name} = typeof {name}Values[number]']
lines += ['export type Ablation = "drop_n" | "drop_u" | "drop_c" | "drop_t" | "equal_utility"',
          'export interface SchedulerConfig { alpha: number; beta_verify: number; beta_risk: number; w0: number; wn: number; wu: number; wc: number; max_feedback_rounds: number; ablations: Ablation[] }',
          'export const defaultSchedulerConfig: SchedulerConfig = ' + json.dumps(SchedulerConfig().model_dump(), ensure_ascii=False)]
content = '\n'.join(lines) + '\n'
target = ROOT / 'src/types/research-contracts.ts'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        raise SystemExit('Python/TypeScript contracts have drifted; run scripts/export_contracts.py')
else:
    target.write_text(content, encoding='utf-8')
print('Contract enums/defaults aligned')
